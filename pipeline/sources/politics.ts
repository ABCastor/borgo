// Where a place sits from left to right, from how it voted at its latest national lower-house election.
//
// Votes: the electoral authority's (or statistics office's) official result, entered by hand in
// pipeline/inputs/politics.json with its URL and the date it was checked. Regions with their own official count (Swiss
// cantons, Canadian provinces, Australian states) have their own rows.
// Party positions: ParlGov 2024 (Döring and Manow, doi:10.7910/DVN/2VZ5ZC, CC0), 0 left to 10 right, matched by the
// ParlGov party id written beside each party. ParlGov's figure is the mean of expert surveys where they cover the
// party, and its party family's mean where they do not; the table keeps which. An alliance takes its members' mean.
// Nothing else is imputed: a party without a ParlGov figure has no position (method in docs/positions.md).
//
// Writes src/fetch/politics-table.ts, read by the politics fetcher for any place in a covered country.
import { DatabaseSync } from "node:sqlite";
import { mkdir, writeFile } from "node:fs/promises";
import { existsSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { ROOT, UA, readJson } from "../lib.ts";
import { positionResult, type ElectionResult, type PartyEstimate } from "../position-results.ts";

const CACHE = join(tmpdir(), "borgo-pipeline");
const PARLGOV_DB = "https://dataverse.harvard.edu/api/access/datafile/10437086"; // ParlGov 2024 release, stable, CC0

async function parlgov(): Promise<Map<number, PartyEstimate>> {
  await mkdir(CACHE, { recursive: true });
  const path = join(CACHE, "parlgov-2024-stable.db");
  if (!existsSync(path)) {
    const res = await fetch(PARLGOV_DB, { headers: { "User-Agent": UA } });
    if (!res.ok) throw new Error(`ParlGov download: ${res.status}`);
    await writeFile(path, new Uint8Array(await res.arrayBuffer()));
  }
  const db = new DatabaseSync(path, { readOnly: true });
  const rows = db
    .prepare(`SELECT p.id id, i.iso2 country, p.name_english name, p.family_id family, v.left_right lr, v.state_market sm, v.liberty_authority la
      FROM party p JOIN country c ON c.id = p.country_id JOIN external_country_iso i ON i.iso3 = c.name_short
      JOIN viewcalc_party_position v ON v.party_id = p.id WHERE v.left_right IS NOT NULL`)
    .all() as unknown as { id: number; country: string; name: string; family: number; lr: number; sm: number; la: number }[];
  db.close();
  // ParlGov gives a party no expert survey covers its family's mean on every scale: one shared tuple per family.
  const key = (r: (typeof rows)[number]) => `${r.family}|${r.lr}|${r.sm}|${r.la}`;
  const count = new Map<string, number>();
  for (const r of rows) count.set(key(r), (count.get(key(r)) ?? 0) + 1);
  return new Map(rows.map((r) => [r.id, { id: r.id, country: r.country, name: r.name, position: r.lr, family: count.get(key(r))! >= 3 }]));
}

const parties = await parlgov();
const results = await readJson<ElectionResult[]>("pipeline/inputs/politics.json");
const entries = results.map((r) => [r.place, positionResult(r, parties)] as const).sort(([a], [b]) => a.localeCompare(b));
if (new Set(entries.map(([place]) => place)).size !== entries.length) throw new Error("Duplicate electorate");

for (const [place, t] of entries) console.log(place.padEnd(7), String(t.position ?? "-").padStart(4), `${Math.round(t.covered * 100)}%`.padStart(5), t.date, t.parties.slice(0, 6).map((p) => `${p.name} ${p.share}% ${p.position ?? "?"}${p.basis === "family" ? "f" : p.basis === "members" ? "m" : ""}`).join("; ").slice(0, 150));

await writeFile(join(ROOT, "src/fetch/politics-table.ts"), `// Generated by pipeline/sources/politics.ts from pipeline/inputs/politics.json; do not edit by hand. Method in docs/positions.md.
import type { PlacePolitics } from "./politics.ts";

/** By ISO country code, or ISO 3166-2 region where the official result is published by region. */
export const POLITICS: Record<string, PlacePolitics> = ${JSON.stringify(Object.fromEntries(entries), null, 2)};
`);
console.log(`politics: ${entries.length} official results, ${entries.filter(([, p]) => p.position !== null).length} with a figure`);
