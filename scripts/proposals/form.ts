// Writes the issue form .github/ISSUE_TEMPLATE/proposal.yml from the proposal fields (src/community/proposal.ts),
// so the form, the parser and the prefilled links cannot drift apart. Usage: node scripts/proposals/form.ts [--check]
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { FIELDS, GRANT_LABEL } from "../../src/community/proposal.ts";
import { REPO_ROOT } from "../../src/community/repo.ts";

const q = (s: string) => JSON.stringify(s);

export function formYaml(): string {
  const intro = [
    "Propose a correction to a figure, a rule or a source. Cite the official text it comes from: the statute, the official gazette, the official table or page. A news article can lead to it but is not a citation, and link-only sites (Numbeo, WeatherSpark and the others marked link-only in the registry) cannot be cited.",
    "",
    "This issue is public and stays under your account: leave out personal details. A check runs on every edit and says what to fix. Nothing reaches the site until a reviewed pull request merges. See CONTRIBUTING.md.",
  ].join("\n");
  const lines = [
    "# Generated by scripts/proposals/form.ts from src/community/proposal.ts; edit those, not this file.",
    "name: Propose a correction",
    "description: Correct a figure, a rule or a source, citing the official text it comes from.",
    `title: ${q("Correction: ")}`,
    "labels: [proposal]",
    "body:",
    "  - type: markdown",
    "    attributes:",
    `      value: ${q(intro)}`,
  ];
  for (const f of FIELDS) {
    lines.push(`  - type: ${f.type}`, `    id: ${f.id}`, "    attributes:", `      label: ${q(f.label)}`, `      description: ${q(f.description)}`);
    if (f.type === "checkboxes") lines.push("      options:", `        - label: ${q(GRANT_LABEL)}`, "          required: true");
    else if (f.placeholder) lines.push(`      placeholder: ${q(f.placeholder)}`);
    if (f.type !== "checkboxes") lines.push("    validations:", `      required: ${f.required ? "true" : "false"}`);
  }
  return `${lines.join("\n")}\n`;
}

const path = join(REPO_ROOT, ".github/ISSUE_TEMPLATE/proposal.yml");
if (import.meta.main) {
  if (process.argv.includes("--check")) {
    if (readFileSync(path, "utf8") !== formYaml()) {
      console.error("The issue form is out of date: run node scripts/proposals/form.ts");
      process.exit(1);
    }
  } else writeFileSync(path, formYaml());
}
